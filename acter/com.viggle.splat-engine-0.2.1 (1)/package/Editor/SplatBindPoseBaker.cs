// Bakes the Generic-mode bind pose into Runtime/SplatSkeletonBindPose.cs so the
// plugin works with zero setup — no bind-pose FBX/clip to assign.
//
// One-time use: select the bind-pose AnimationClip (inside skel441_bindpose.fbx,
// imported as Generic) and run "Assets/Viggle/Bake Generic Bind Pose". The clip is
// sampled through Unity's own importer onto a temp rig, so the baked values carry
// exactly the conventions Generic animation clips will play with. Re-bake only if
// the GLB->FBX export pipeline's axis/unit conventions change.
//
// Bakes the 86 BODY bones (SplatSkeleton.Body86) - the only ones any current Generic
// clip drives. A full-bin character in Generic mode uses this same table for its body
// and leaves its facial bones at their rest locals, which is exact for body-only
// clips (see SplatSkeletonBindPose). Baking the full rig only becomes necessary the
// day a Generic clip animates facial bones; point kSkeleton at Full441 then.

using System.Globalization;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace Viggle.SplatEngine.EditorTools
{
    internal static class SplatBindPoseBaker
    {
        const string kOutPath = "Packages/com.viggle.splat-engine/Runtime/SplatSkeletonBindPose.cs";
        const string kPrefixName = "Armature"; // must match SplatRigBuilder's generic path prefix
        // The rig the bind pose is sampled onto; see the header for why it is the body rig.
        static readonly SplatSkeletonDef kSkeleton = SplatSkeleton.Body86;

        [MenuItem("Assets/Viggle/Bake Generic Bind Pose", true)]
        static bool Validate() => Selection.activeObject is AnimationClip;

        [MenuItem("Assets/Viggle/Bake Generic Bind Pose")]
        static void Bake()
        {
            var clip = (AnimationClip)Selection.activeObject;

            // Temp rig mirroring SkinnedSplatRenderer.BuildRig (Generic): root -> prefix -> bones.
            var root = new GameObject("BindPoseBakeRig");
            try
            {
                var prefix = new GameObject(kPrefixName).transform;
                prefix.SetParent(root.transform, false);
                int n = kSkeleton.NumBones;
                var bones = new Transform[n];
                for (int i = 0; i < n; i++)
                {
                    var t = new GameObject(kSkeleton.Names[i]).transform;
                    int p = kSkeleton.Parents[i];
                    t.SetParent(p >= 0 ? bones[p] : prefix, false);
                    t.localPosition = kSkeleton.LocalPosition(i);
                    t.localRotation = kSkeleton.LocalRotation(i);
                    bones[i] = t;
                }

                clip.SampleAnimation(root, 0f);

                var sb = new StringBuilder();
                var ci = CultureInfo.InvariantCulture;
                string F(float v) => v.ToString("R", ci) + "f";
                string V3(Vector3 v) => $"new Vector3({F(v.x)}, {F(v.y)}, {F(v.z)})";
                string Q(Quaternion q) => $"new Quaternion({F(q.x)}, {F(q.y)}, {F(q.z)}, {F(q.w)})";

                sb.AppendLine("// SPDX-License-Identifier: MIT");
                sb.AppendLine("// AUTO-GENERATED by SplatBindPoseBaker (\"Assets/Viggle/Bake Generic Bind Pose\") — do not edit.");
                sb.AppendLine($"// Source clip: {AssetDatabase.GetAssetPath(clip)} | baked from {n} bones.");
                sb.AppendLine("//");
                sb.AppendLine("// The canonical bind pose expressed in the Generic animation clips' conventions,");
                sb.AppendLine("// as sampled through Unity's own FBX import. Embedding it lets SplatCharacterSkinner");
                sb.AppendLine("// capture a correct inverse-bind for Generic playback without the user assigning a");
                sb.AppendLine("// bind-pose clip. Re-bake only if the GLB->FBX export pipeline's conventions change.");
                sb.AppendLine("//");
                sb.AppendLine("// Covers the 86 BODY bones only. On a full-bin (441-bone) character Apply poses those");
                sb.AppendLine("// and leaves the facial bones at their rest locals - exact for any clip that does not");
                sb.AppendLine("// animate facial bones, because a bone whose local never changes ends up with its body");
                sb.AppendLine("// ancestor's skinning matrix, i.e. the face rides the head. Facial animation in Generic");
                sb.AppendLine("// mode would need a 441-bone re-bake (see SplatBindPoseBaker).");
                sb.AppendLine();
                sb.AppendLine("using UnityEngine;");
                sb.AppendLine();
                sb.AppendLine("namespace Viggle.SplatEngine");
                sb.AppendLine("{");
                sb.AppendLine("    internal static class SplatSkeletonBindPose");
                sb.AppendLine("    {");
                sb.AppendLine("        /// True once the table has been baked; false in the placeholder.");
                sb.AppendLine("        public static bool HasData => T.Length > 0;");
                sb.AppendLine();
                sb.AppendLine("        // Prefix (\"Armature\") node local TRS at bind.");
                sb.AppendLine($"        public static readonly Vector3 PrefixPosition = {V3(prefix.localPosition)};");
                sb.AppendLine($"        public static readonly Quaternion PrefixRotation = {Q(prefix.localRotation)};");
                sb.AppendLine($"        public static readonly Vector3 PrefixScale = {V3(prefix.localScale)};");
                sb.AppendLine();
                sb.AppendLine("        // Per-bone local TRS at bind, indexed like the rig's Names: T = xyz, R = xyzw.");
                sb.Append("        static readonly float[] T = {");
                for (int i = 0; i < n; i++)
                {
                    var p = bones[i].localPosition;
                    sb.Append(i % 4 == 0 ? "\n            " : " ");
                    sb.Append($"{F(p.x)}, {F(p.y)}, {F(p.z)},");
                }
                sb.AppendLine("\n        };");
                sb.Append("        static readonly float[] R = {");
                for (int i = 0; i < n; i++)
                {
                    var q = bones[i].localRotation;
                    sb.Append(i % 3 == 0 ? "\n            " : " ");
                    sb.Append($"{F(q.x)}, {F(q.y)}, {F(q.z)}, {F(q.w)},");
                }
                sb.AppendLine("\n        };");
                sb.AppendLine(@"
        /// Pose `bones` (indexed like the rig they were built from) and the optional prefix
        /// node to the baked bind pose. Bones past the baked count - the facial bones of a
        /// full rig - are left as they are. No-op when not baked.
        public static void Apply(Transform[] bones, Transform prefix)
        {
            if (!HasData) return;
            if (prefix != null)
            {
                prefix.localPosition = PrefixPosition;
                prefix.localRotation = PrefixRotation;
                prefix.localScale = PrefixScale;
            }
            int n = Mathf.Min(bones.Length, T.Length / 3);
            for (int i = 0; i < n; i++)
            {
                if (bones[i] == null) continue;
                bones[i].localPosition = new Vector3(T[i * 3], T[i * 3 + 1], T[i * 3 + 2]);
                bones[i].localRotation = new Quaternion(R[i * 4], R[i * 4 + 1], R[i * 4 + 2], R[i * 4 + 3]);
            }
        }
    }
}");

                File.WriteAllText(kOutPath, sb.ToString());
                AssetDatabase.Refresh();
                Debug.Log($"SplatBindPoseBaker: baked {n} bones from '{clip.name}' into {kOutPath}. " +
                          "Generic mode no longer needs a bind-pose clip assigned.");
            }
            finally
            {
                Object.DestroyImmediate(root);
            }
        }
    }
}
